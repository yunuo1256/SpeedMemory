    def __init__(self, lang="en"):
        self.lang = lang if lang in LANGS else "en"

    def set(self, lang):
        if lang in LANGS:
            self.lang = lang

    def __call__(self, key, **kw):
        table = TEXT.get(self.lang, TEXT["en"])
        s = table.get(key, TEXT["en"].get(key, key))
        return s.format(**kw) if kw else s
